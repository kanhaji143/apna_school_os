const { getDb, PRIMARY_DB_PATH, VAULT_DB_PATH } = require('../database/db');
const fs = require('node:fs');
const path = require('node:path');

class BackupEODService {
    static generateEODReport() {
        const db = getDb();
        const profile = db.prepare('SELECT * FROM institution_profile WHERE id = 1').get();
        const today = new Date().toISOString().slice(0, 10);

        // Today's Admissions
        const admissions = db.prepare(`
            SELECT admission_no, student_name, father_name, class, section, mobile
            FROM students
            WHERE admission_date = ?
        `).all(today);

        // Today's Collections
        const collections = db.prepare(`
            SELECT ft.receipt_no, ft.amount_received, ft.payment_mode, s.student_name, s.class
            FROM fee_transactions ft
            JOIN students s ON ft.student_id = s.id
            WHERE ft.payment_date = ? AND ft.status = 'Paid'
        `).all(today);

        const totalCollection = collections.reduce((sum, c) => sum + (c.amount_received || 0), 0);

        // Today's Expenses
        const expenses = db.prepare(`
            SELECT voucher_no, category, description, amount, paid_to
            FROM expenses
            WHERE expense_date = ?
        `).all(today);

        const totalExpense = expenses.reduce((sum, e) => sum + (e.amount || 0), 0);
        const netSavings = totalCollection - totalExpense;

        // Zero-Password Gmail Compose URL
        const subject = encodeURIComponent(`Daily EOD Report - ${profile.school_name} (${today})`);
        const body = encodeURIComponent(
            `Respected Director / Owner,\n\n` +
            `Here is the automated daily summary for ${today}:\n\n` +
            `📌 Today's New Admissions: ${admissions.length}\n` +
            `💰 Today's Total Fee Collection: ₹${totalCollection.toLocaleString('en-IN')}\n` +
            `💸 Today's Total Expenses: ₹${totalExpense.toLocaleString('en-IN')}\n` +
            `📈 Today's Net Balance: ₹${netSavings.toLocaleString('en-IN')}\n\n` +
            `Generated by APNA Computer RMS Enterprise v2.0\n` +
            `Helpline: 8504985149`
        );
        const gmailUrl = `https://mail.google.com/mail/?view=cm&fs=1&to=${encodeURIComponent(profile.email || 'director@gmail.com')}&su=${subject}&body=${body}`;

        return {
            today,
            institution: profile,
            admissions,
            collections,
            totalCollection,
            expenses,
            totalExpense,
            netSavings,
            gmail_url: gmailUrl
        };
    }

    static createPenDriveBackup(targetDir) {
        if (!fs.existsSync(targetDir)) {
            throw new Error(`Target backup directory does not exist: ${targetDir}`);
        }

        const timestamp = new Date().toISOString().replace(/[:.]/g, '-');
        const backupFileName = `APNA_RMS_FULL_BACKUP_${timestamp}.db`;
        const destPath = path.join(targetDir, backupFileName);

        fs.copyFileSync(PRIMARY_DB_PATH, destPath);

        return {
            success: true,
            backup_path: destPath,
            timestamp
        };
    }
}

module.exports = BackupEODService;
